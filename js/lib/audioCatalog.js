/**
 * Returns audio streaming link for specific book, test, and part
 * @param {string|number} book Book number (e.g. '18', '19', '20')
 * @param {string|number} test Test number (1-4)
 * @param {string|number} part Part number (1-4)
 * @returns {string|null} SharePoint streaming URL
 */
export function getAudioStreamUrl(book, test, part) {
  const b = String(book);
  const t = String(test);
  const p = String(part);
  return audioCatalog[b]?.[t]?.[p] || null;
}

/**
 * Identifies if a given track is one of the known duplicate URLs
 */
export function isDuplicateTrack(book, test, part) {
  const key = `${book}-${test}-${part}`;
  return key === '19-1-2' || key === '19-1-3' || key === '19-2-2' || key === '19-2-3';
}
